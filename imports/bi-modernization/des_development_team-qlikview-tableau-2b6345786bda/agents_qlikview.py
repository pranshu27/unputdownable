# Module-level mapping: JSON result key -> aggregated_results key
_PHASE1_KEY_MAP = {
    "data_sources":           _KEY_DATA_SOURCES,
    "data_model":             _KEY_DATA_MODEL,
    "data_transformations":   _KEY_DATA_TRANSFORMATIONS,
    "hierarchies":            "Hierarchies",
    "Visualizations":         "Visualizations",
    "filters":                "Filters",
    "parameters_variables":   _KEY_PARAMS_VARS,
    "sheets":                 "Sheets",
    "dashboards":             "Dashboards",
    "relationships":          "Relationships",
    "tables":                 "Enhanced Tables",
    "calculations":           "Calculation Dependencies",
}


async def _aggregate_phase1_results(q: asyncio.Queue) -> dict:
    """Drain the queue and return the aggregated Phase 1 results dict."""
    aggregated_results = {v: [] for v in _PHASE1_KEY_MAP.values()}

    while not q.empty():
        result = await q.get()
        result_json = json.loads(result.content)
        print("result_json:", result_json)

        for src_key, dst_key in _PHASE1_KEY_MAP.items():
            if src_key in result_json:
                aggregated_results[dst_key].extend(result_json[src_key])

    return aggregated_results


async def _run_phase2_extraction(
    runtime,
    aggregated_results: dict,
    loadscript_content: str,
) -> None:
    """Publish all Phase 2 (enhanced extraction) messages to the runtime."""
    context_for_enhancement = {
        "data_sources": aggregated_results[_KEY_DATA_SOURCES],
        "data_model": aggregated_results[_KEY_DATA_MODEL],
        "data_transformations": aggregated_results[_KEY_DATA_TRANSFORMATIONS],
        "visualizations": aggregated_results["Visualizations"],
        "parameters_variables": aggregated_results[_KEY_PARAMS_VARS],
    }

    print("\n--- Extracting Data Sources (Common Model Format) ---")
    data_sources_context = (
        f"Data Sources (Phase 1):\n"
        f"{json.dumps(context_for_enhancement['data_sources'], indent=2)}\n\n"
        f"LoadScript:\n{loadscript_content}\n"
    )
    await runtime.publish_message(
        FlowRequest(content=data_sources_context, extraction_type="data_sources_common"),
        topic_id=TopicId("QlikViewMetadataExtractor", source="enhanced")
    )

    print("\n--- Extracting Relationships ---")
    relationships_context = (
        f"LoadScript:\n{loadscript_content}\n\n"
        f"Data Model:\n{json.dumps(context_for_enhancement['data_model'], indent=2)}\n\n"
        f"Visualizations (showing field usage):\n"
        f"{json.dumps(context_for_enhancement['visualizations'], indent=2)}\n"
    )
    await runtime.publish_message(
        FlowRequest(content=relationships_context, extraction_type="relationships"),
        topic_id=TopicId("QlikViewMetadataExtractor", source="enhanced")
    )

    print("\n--- Extracting Enhanced Table Metadata ---")
    enhanced_tables_context = (
        f"Data Model:\n{json.dumps(context_for_enhancement['data_model'], indent=2)}\n\n"
        f"LoadScript:\n{loadscript_content}\n\n"
        f"Data Transformations:\n"
        f"{json.dumps(context_for_enhancement['data_transformations'], indent=2)}\n\n"
        f"Visualizations (showing field usage):\n"
        f"{json.dumps(context_for_enhancement['visualizations'], indent=2)}\n"
    )
    await runtime.publish_message(
        FlowRequest(content=enhanced_tables_context, extraction_type="enhanced_tables"),
        topic_id=TopicId("QlikViewMetadataExtractor", source="enhanced")
    )

    print("\n--- Extracting Calculation Dependencies ---")
    calculations_context = (
        f"Data Transformations:\n"
        f"{json.dumps(context_for_enhancement['data_transformations'], indent=2)}\n\n"
        f"Visualizations (with chart expressions):\n"
        f"{json.dumps(context_for_enhancement['visualizations'], indent=2)}\n\n"
        f"Parameters or Variables:\n"
        f"{json.dumps(context_for_enhancement['parameters_variables'], indent=2)}\n\n"
        f"LoadScript (for inline calculations):\n{loadscript_content}\n"
    )
    await runtime.publish_message(
        FlowRequest(content=calculations_context, extraction_type="calculation_dependencies"),
        topic_id=TopicId("QlikViewMetadataExtractor", source="enhanced")
    )


async def _collect_phase2_results(q: asyncio.Queue) -> dict:
    """Drain the queue and return Phase 2 results in Common Model format."""
    phase2_results = {
        "data_sources": [],
        "tables": [],
        "relationships": [],
        "calculations": [],
    }

    while not q.empty():
        result = await q.get()
        result_json = json.loads(result.content)

        if "data_sources" in result_json:
            phase2_results["data_sources"].extend(result_json["data_sources"])
        if "relationships" in result_json:
            phase2_results["relationships"].extend(result_json["relationships"])
        if "tables" in result_json:
            phase2_results["tables"].extend(result_json["tables"])
        if "calculations" in result_json:
            phase2_results["calculations"].extend(result_json["calculations"])

    return phase2_results


