def _build_file_maps(file_paths: List[str]) -> dict:
    """Return a dict of all categorised file lists derived from file_paths."""
    visualization_prefixes = ["TB", "CH", "CS", "TX"]
    filter_prefixes = ["LB", "MB"]
    object_prefixes = [
        "TB", "CH", "CS", "TX",
        "BU", "IB", "SL", "BM", "CT", "SO",
        "LB", "MB",
    ]
    dashboards_prefixes = ["SH"]
    sheet_prefixes = ["SH"]

    return {
        "data_extract_files": [p for p in file_paths if p.endswith("LoadScript.txt")],
        "visualization_files": [p for p in file_paths if os.path.basename(p).startswith(tuple(visualization_prefixes))],
        "param_variable_files": [p for p in file_paths if p.endswith(("AllProperties.xml", "DocInternal.xml"))],
        "dashboards_files": [p for p in file_paths if os.path.basename(p).startswith(tuple(dashboards_prefixes))],
        "filter_files": [p for p in file_paths if os.path.basename(p).startswith(tuple(filter_prefixes))],
        "sheet_files": [p for p in file_paths if os.path.basename(p).startswith(tuple(sheet_prefixes))],
        "object_files": [p for p in file_paths if os.path.basename(p).startswith(tuple(object_prefixes))],
        "hierarchies_files": [p for p in file_paths if p.endswith("AllProperties.xml")],
    }


# ---------------------------------------------------------------------------
# Helper: extract object names from XML files
# ---------------------------------------------------------------------------

def _extract_name_from_ch_file(file_path: str) -> str:
    tree = ET.parse(file_path)
    root = tree.getroot()
    name_value = root.findtext(".//Name/v")
    if name_value is None:
        name_value = root.findtext(".//Text/v")
    return name_value


def _extract_object_names(object_files: List[str]) -> dict:
    """Return {object_id: name} for all object XML files that have a name."""
    names = {}
    for path in object_files:
        object_id = os.path.basename(path)
        name = _extract_name_from_ch_file(path)
        if name:
            names[object_id] = name
    return names


