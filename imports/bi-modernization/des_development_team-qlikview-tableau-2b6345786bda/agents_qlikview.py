async def run_single_tenant_flow_processor(file_paths):

    file_maps = _build_file_maps(file_paths)
    data_extract_files = file_maps["data_extract_files"]
    visualization_files = file_maps["visualization_files"]
    param_variable_files = file_maps["param_variable_files"]
    dashboards_files = file_maps["dashboards_files"]
    filter_files = file_maps["filter_files"]
    sheet_files = file_maps["sheet_files"]
    object_files = file_maps["object_files"]
    hierarchies_files = file_maps["hierarchies_files"]

    names = _extract_object_names(object_files)
    print(names)

    # Per-call queues — avoids cross-contamination when batch processes
    # multiple QlikView files concurrently.
    result_queue: asyncio.Queue[TaskResponse] = asyncio.Queue()
    exe_queue: asyncio.Queue[ExecutiveSummaryResponse] = asyncio.Queue()

    # Setup Autogen Core runtime
    runtime = SingleThreadedAgentRuntime()

    # Register single agent
    await QlikViewMetadataExtractorAgent.register(
        runtime,
        type="QlikViewMetadataExtractor",
        factory=lambda: QlikViewMetadataExtractorAgent(),
    )

    # ExecutiveSummaryAgent is only used later in its own runtime invocation;
    # do NOT register save_executive_summary here — it would receive TaskResponse
    # messages and log spurious type-mismatch warnings.
    await ClosureAgent.register_closure(
        runtime,
        "collect_result_agent",
        _make_collect_result(result_queue),
        subscriptions=lambda: [DefaultSubscription()],
    )

    async def process_files(file_map: dict, runtime, topic_name="QlikViewMetadataExtractor", source="default"):
        for extraction_type, files in file_map.items():
            for file_path in files:
                try:
                    async with aiofiles.open(file_path, 'r', encoding="utf-8") as f:
                        content = await f.read()
                    print(f"\nProcessing {extraction_type} file: {file_path}")
                    await runtime.publish_message(
                        FlowRequest(content=content, extraction_type=extraction_type),
                        topic_id=TopicId(topic_name, source=source)
                    )
                except Exception as e:
                    print(f"Error processing {file_path} for {extraction_type}: {e}")

    file_map = {
        "dataextractor": data_extract_files,
        "parameters_variables": param_variable_files,
    }

    runtime.start()

    await process_files(file_map, runtime)

    file_path = [path for path in file_paths if path.endswith(("QlikViewProject.xml"))]
    async with aiofiles.open(file_path[0], 'r', encoding="utf-8") as file:
        file_contents = await file.read()

    await _publish_visualization_files(runtime, visualization_files, file_contents)
    await _publish_filter_files(runtime, filter_files, file_contents)
    await _publish_dashboard_files(runtime, dashboards_files, file_contents, names)
    await _publish_sheet_files(runtime, sheet_files)
    await _publish_hierarchy_files(runtime, hierarchies_files)

    await runtime.stop_when_idle()

    # Aggregate Phase 1 results
    aggregated_results = await _aggregate_phase1_results(result_queue)

    # ============================================================================
    # PHASE 2: ENHANCED EXTRACTION (Relationships, Enhanced Tables, Calculations)
    # ============================================================================
    print("\n" + "="*80)
    print("PHASE 2: Running Enhanced Extraction for Common Model Alignment")
    print("="*80 + "\n")

    runtime.start()

    # Get LoadScript content for enhanced extraction
    loadscript_content = ""
    if data_extract_files:
        async with aiofiles.open(data_extract_files[0], 'r', encoding="utf-8") as f:
            loadscript_content = await f.read()

    await _run_phase2_extraction(runtime, aggregated_results, loadscript_content)

    await runtime.stop_when_idle()

    # Collect Phase 2 results
    print("\n--- Collecting Phase 2 Results (Common Model Format) ---")
    phase2_results = await _collect_phase2_results(result_queue)

    print("\n" + "="*80)
    print("Phase 2 Extraction Complete (Common Model Format)!")
    print(f"  - Data Sources: {len(phase2_results['data_sources'])}")
    print(f"  - Tables: {len(phase2_results['tables'])}")
    print(f"  - Relationships: {len(phase2_results['relationships'])}")
    print(f"  - Calculations: {len(phase2_results['calculations'])}")
    print("="*80 + "\n")

    # Continue with executive summary generation in a dedicated runtime
    exe_runtime = SingleThreadedAgentRuntime()
    await ExecutiveSummaryAgent.register(
        exe_runtime,
        type=executive_summary_topic_type,
        factory=lambda: ExecutiveSummaryAgent(),
    )
    await ClosureAgent.register_closure(
        exe_runtime,
        "save_executive_summary",
        _make_save_executive_summary(exe_queue),
        subscriptions=lambda: [DefaultSubscription()],
    )
    exe_runtime.start()

    await exe_runtime.publish_message(
        Request(content=json.dumps(aggregated_results)),
        topic_id=TopicId(executive_summary_topic_type, source="default"),
    )

    await exe_runtime.stop_when_idle()

    while not exe_queue.empty():
        data = (await exe_queue.get()).content
        print("----------------------", data)
        aggregated_results["executivesummary"] = data

    # ============================================================================
    # MERGE PHASE 1 + PHASE 2 INTO COMMON MODEL
    # ============================================================================
    print("\n" + "="*80)
    print("Merging Phase 1 + Phase 2 into Common Model")
    print("="*80 + "\n")

    from common_model_merger import merge_qlikview_results

    common_model = merge_qlikview_results(
        phase1_output=aggregated_results,
        phase2_output=phase2_results
    )

    # Carry the executive/technical summary into the final model so handlers
    # can derive ai_summary from it.
    common_model["technical_summary"] = aggregated_results.get("executivesummary", "")

    print("✅ Common Model merge complete!")
    print("="*80 + "\n")

    return common_model
